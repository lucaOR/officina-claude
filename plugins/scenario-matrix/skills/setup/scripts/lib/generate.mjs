import { readFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

export const HEADER = '// generated by scenario-matrix setup: do not edit; run setup.mjs regen\n';
const FACADE_FILES = ['observe.mjs', 'fault.mjs'];
const ident = name => `adapter_${name.replace(/\W/g, '_')}`;

// adapters.mjs: each chosen adapter's contribution module as a namespace, and the facade-name
// provider map over the whole catalog so a facade can tell the user which adapter to add.
export function adaptersModule(chosen, catalog) {
  const providers = {};
  for (const spec of catalog.adapters.values()) {
    const names = [...FACADE_FILES.flatMap(f => spec.exports?.[f] ?? []), ...(spec.drivers ?? [])];
    for (const n of names) {
      providers[n] ??= [];
      if (!providers[n].includes(spec.name)) providers[n].push(spec.name);
    }
  }
  for (const list of Object.values(providers)) list.sort();
  const imports = chosen.map(a => `import * as ${ident(a.name)} from './adapter-${a.name}.mjs';\n`).join('');
  const entries = chosen.map(a => `  ${JSON.stringify(a.name)}: ${ident(a.name)},\n`).join('');
  const adapters = chosen.length ? `{\n${entries}}` : '{}';
  const sorted = Object.fromEntries(Object.entries(providers).sort(([x], [y]) => x.localeCompare(y)));
  const prov = Object.keys(sorted).length ? JSON.stringify(sorted, null, 2) : '{}';
  return `${HEADER}${imports}\nexport const ADAPTERS = ${adapters};\nexport const PROVIDERS = ${prov};\n`;
}

// project-exports.mjs may hold only `export { a, b as c } from './x.mjs';` statements.
export function parseProjectExports(text) {
  const out = [];
  const stmt = /^export\s*\{([^}]*)\}\s*from\s*'(\.\/[^']+)'\s*;?$/;
  text.split('\n').forEach((raw, i) => {
    const line = i + 1;
    const src = raw.trim();
    if (!src || src.startsWith('//')) return;
    if (/^export\s*\{\s*\}\s*;?$/.test(src)) return; // the empty placeholder
    if (/^export\s*\*/.test(src)) throw new Error(`project-exports.mjs:${line}: export * is not allowed, name each export: ${src}`);
    const m = stmt.exec(src);
    if (!m) throw new Error(`project-exports.mjs:${line}: only "export { a, b as c } from './x.mjs';" is allowed: ${src}`);
    for (const item of m[1].split(',').map(s => s.trim()).filter(Boolean)) {
      const parts = /^(\w+)(?:\s+as\s+(\w+))?$/.exec(item);
      if (!parts) throw new Error(`project-exports.mjs:${line}: cannot read export "${item}"`);
      out.push({ name: parts[2] ?? parts[1], local: parts[1], from: m[2], line });
    }
  });
  return out;
}

// index.mjs: core exports, then each adapter in resolved order, then everything from project-exports.
export function indexModule({ core, chosen, projectExports }) {
  const seen = new Map(); // name -> file
  const claim = (name, file) => {
    const prior = seen.get(name);
    if (prior === undefined) { seen.set(name, file); return true; }
    if (prior === file) return false;
    throw new Error(`duplicate export ${name}: ${prior} and ${file}`);
  };
  const lines = [];
  const add = exportsByFile => {
    for (const [file, names] of Object.entries(exportsByFile ?? {})) {
      const fresh = names.filter(n => claim(n, file));
      if (fresh.length) lines.push(`export { ${fresh.join(', ')} } from './${file}';`);
    }
  };
  add(core.exports);
  for (const a of chosen) add(a.exports);
  for (const p of projectExports) claim(p.name, p.from.replace(/^\.\//, ''));
  lines.push("export * from './project-exports.mjs';");
  return `${HEADER}${lines.join('\n')}\n`;
}

// The harness API page: the core page, each chosen adapter's page in resolved order, then the project's page.
export function harnessApi({ corePage, chosen, projectPage }) {
  const pages = [corePage];
  for (const a of chosen) {
    const file = join(a.dir, a.api ?? 'api.md');
    if (existsSync(file)) pages.push(readFileSync(file, 'utf8'));
  }
  if (projectPage) pages.push(projectPage);
  return pages.map(p => p.trimEnd()).join('\n\n') + '\n';
}
