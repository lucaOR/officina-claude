import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { loadCatalog, resolveAdapters } from '../catalog.mjs';
import { adaptersModule } from '../generate.mjs';
import { pluginFiles } from '../plan.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), 'fixtures', 'catalog');
const catalog = () => loadCatalog(root);

test('loadCatalog reads core.json and every adapter.json with its dir', () => {
  const c = catalog();
  assert.deepEqual(c.core.files, ['core1.mjs']);
  assert.deepEqual([...c.adapters.keys()].sort(), ['a', 'b', 'c']);
  assert.equal(c.adapters.get('a').dir, join(root, 'runtime', 'adapters', 'a'));
});

test('a plugin root with no adapters gives an empty catalog', () => {
  const dir = mkdtempSync(join(tmpdir(), 'scn-cat-'));
  mkdirSync(join(dir, 'runtime', 'core'), { recursive: true });
  writeFileSync(join(dir, 'runtime', 'core', 'core.json'), '{"files":[],"exports":{},"tests":[]}');
  assert.equal(loadCatalog(dir).adapters.size, 0);
});

test('requires are added and ordered first', () => {
  assert.deepEqual(resolveAdapters(catalog(), ['c']).map(a => a.name), ['a', 'b', 'c']);
});

test('ties break alphabetically and duplicates collapse', () => {
  assert.deepEqual(resolveAdapters(catalog(), ['b', 'a', 'a']).map(a => a.name), ['a', 'b']);
});

test('an unknown adapter names the catalog', () => {
  assert.throws(() => resolveAdapters(catalog(), ['zzz']), /unknown adapter: zzz \(catalog: a, b, c\)/);
});

test('PROVIDERS lists every catalog adapter that exports a facade name', () => {
  const c = catalog();
  const src = adaptersModule(resolveAdapters(c, ['a']), c);
  assert.match(src, /^\/\/ generated by scenario-matrix setup: do not edit; run setup\.mjs regen/);
  const providers = JSON.parse(/export const PROVIDERS = (\{[\s\S]*?\});\n/.exec(src)[1]);
  assert.deepEqual(providers.race, ['b']);
  assert.deepEqual(providers.cdrv, ['c']);
  assert.equal(providers.aOnly, undefined);
  assert.deepEqual(providers.logs, ['a', 'b']);
  assert.equal(providers.coreFn, undefined);
});

test('an adapter.json whose name differs from its directory is refused', () => {
  const dir = mkdtempSync(join(tmpdir(), 'scn-cat-'));
  mkdirSync(join(dir, 'runtime', 'core'), { recursive: true });
  writeFileSync(join(dir, 'runtime', 'core', 'core.json'), '{"files":[],"exports":{},"tests":[]}');
  mkdirSync(join(dir, 'runtime', 'adapters', 'web'), { recursive: true });
  writeFileSync(join(dir, 'runtime', 'adapters', 'web', 'adapter.json'), '{"name":"http"}');
  assert.throws(() => loadCatalog(dir), /adapters\/web\/adapter\.json names "http"/);
});

test('two sources that would write the same lib path are refused, naming both', () => {
  const dir = mkdtempSync(join(tmpdir(), 'scn-clash-'));
  const src = (name, files, tests) => {
    const d = join(dir, name);
    mkdirSync(join(d, 'test', 'support'), { recursive: true });
    for (const f of files) writeFileSync(join(d, f), '');
    for (const f of tests) writeFileSync(join(d, 'test', f), '');
    return { name, dir: d, files };
  };
  const core = src('core', ['run.mjs'], ['run.test.mjs']);
  assert.throws(() => pluginFiles({ core }, [src('a', ['x.mjs'], ['support/fake.mjs']), src('b', ['y.mjs'], ['support/fake.mjs'])]),
    err => /test\/support\/fake\.mjs/.test(err.message) && err.message.includes(join(dir, 'a')) && err.message.includes(join(dir, 'b')));
  assert.throws(() => pluginFiles({ core }, [src('c', ['run.mjs'], [])]), /run\.mjs/);
  assert.equal(pluginFiles({ core }, [src('d', ['z.mjs'], ['z.test.mjs'])]).length, 4);
});
