import { test } from 'node:test';
import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { loadCatalog, resolveAdapters } from '../catalog.mjs';
import { adaptersModule, parseProjectExports, indexModule, harnessApi } from '../generate.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), 'fixtures', 'catalog');
const catalog = () => loadCatalog(root);
const chosen = names => resolveAdapters(catalog(), names);

test('same name from the same file in two adapters is exported once', () => {
  const src = indexModule({ core: catalog().core, chosen: chosen(['b']), projectExports: [] });
  assert.equal(src.match(/\blogs\b/g).length, 1);
  assert.equal(src.match(/\bnoLog\b/g).length, 1);
});

test('a project export that collides with an adapter export fails naming both files', () => {
  const projectExports = parseProjectExports("export { race } from './mine.mjs';\n");
  assert.throws(() => indexModule({ core: catalog().core, chosen: chosen(['b']), projectExports }),
    /duplicate export race: fault\.mjs and mine\.mjs/);
});

test('the same name from two adapter files is a generation error naming both', () => {
  const c = catalog();
  c.adapters.get('c').exports['a.mjs'] = ['logs'];
  assert.throws(() => indexModule({ core: c.core, chosen: resolveAdapters(c, ['c']), projectExports: [] }),
    /duplicate export logs: (observe\.mjs and a\.mjs|a\.mjs and observe\.mjs)/);
});

test('index lists core, then adapters in resolved order, then export * from project-exports', () => {
  const src = indexModule({ core: catalog().core, chosen: chosen(['c']), projectExports: [] });
  const at = s => src.indexOf(s);
  assert.match(src, /^\/\/ generated by scenario-matrix setup: do not edit; run setup\.mjs regen/);
  assert.ok(at("'./core1.mjs'") > 0);
  assert.ok(at("'./core1.mjs'") < at("'./a.mjs'"));
  assert.ok(at("'./a.mjs'") < at("'./fault.mjs'"));
  assert.ok(at("'./fault.mjs'") < at("'./c.mjs'"));
  assert.ok(src.trimEnd().endsWith("export * from './project-exports.mjs';"));
});

test('parseProjectExports reads names, aliases, sources and lines', () => {
  const got = parseProjectExports("// mine\n\nexport { a, b as c } from './x.mjs';\n");
  assert.deepEqual(got, [
    { name: 'a', local: 'a', from: './x.mjs', line: 3 },
    { name: 'c', local: 'b', from: './x.mjs', line: 3 },
  ]);
});

test('parseProjectExports refuses export * and names the line', () => {
  assert.throws(() => parseProjectExports("export { a } from './x.mjs';\nexport * from './y.mjs';\n"),
    /project-exports\.mjs:2: .*export \*/);
});

test('parseProjectExports refuses anything else and names the line', () => {
  assert.throws(() => parseProjectExports("const x = 1;\n"), /project-exports\.mjs:1: /);
});

test('adapters.mjs imports each chosen adapter module and stays valid when empty', async () => {
  const c = catalog();
  const some = adaptersModule(chosen(['b']), c);
  assert.match(some, /import \* as \w+ from '\.\/adapter-a\.mjs';/);
  assert.match(some, /export const ADAPTERS = \{[^}]*"a"[^}]*"b"/);
  const none = adaptersModule([], { core: c.core, adapters: new Map() });
  assert.match(none, /export const ADAPTERS = \{\};/);
  assert.match(none, /export const PROVIDERS = \{\};/);
});

test('harnessApi joins the core page, each chosen adapter page and the project page', () => {
  const doc = harnessApi({ corePage: 'CORE', chosen: chosen(['b']), projectPage: 'PROJ' });
  assert.ok(doc.indexOf('CORE') < doc.indexOf('# a api'));
  assert.ok(doc.indexOf('# a api') < doc.indexOf('# b api'));
  assert.ok(doc.indexOf('# b api') < doc.indexOf('PROJ'));
});
